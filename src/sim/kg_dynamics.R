kg_dyn_build_planned_timing = function(baseline_cells, tau_S_mat, years,
                                       tau_B_mat = NULL,
                                       timeable_share = kg_dyn_active_timeable_share(),
                                       timing_window = KG_DYN_TIMING_WINDOW,
                                       ref_wedge     = KG_DYN_TIMING_REF_WEDGE,
                                       ages_bathtub = KG_DYN_AGE_MIN:
                                                      KG_DYN_AGE_MAX,
                                       tie_tol = 1e-12) {

  # The short-run timing overlay (spec v3). For each (age, source-year u), the
  # timeable share of baseline dollars (timeable_share * R_B, drawn from the
  # WHOLE pool) looks at the policy-induced wedge tau_S - tau_B over [u-H, u+H]
  # and routes toward the best year v* (lowest wedge; ties broken by nearest,
  # then earlier). Move fraction = clamp((wedge[u] - wedge[v*]) / ref_wedge, 0,
  # 1); the complement stays at u. Using tau_S - tau_B (not just tau_S) keeps
  # the rule policy-driven so baseline-only runs don't retime dollars.
  # Callers pass the LAW-ONLY reform tau (aggregated from mtr_kg_lt_lawonly) as
  # tau_S_mat, so the wedge is statutory-only and identically zero when the
  # living-side schedule matches baseline.

  kg_dyn_validate_timing_params(timeable_share = timeable_share,
                                timing_window  = timing_window,
                                ref_wedge      = ref_wedge)

  ages_chr  = as.character(ages_bathtub)
  years_chr = as.character(years)
  n_ages    = length(ages_bathtub)
  n_years   = length(years)
  H         = as.integer(timing_window)

  R_B = matrix(0, n_ages, n_years, dimnames = list(ages_chr, years_chr))
  for (t_chr in years_chr) {
    bt = baseline_cells[[t_chr]]
    R_B[, t_chr] = bt$R_B[match(ages_bathtub, bt$age)]
  }

  R_planned_B = timeable_share * R_B
  R_planned_S = matrix(0, n_ages, n_years,
                       dimnames = list(ages_chr, years_chr))
  timing_tau_mat = if (is.null(tau_B_mat)) tau_S_mat else tau_S_mat - tau_B_mat
  tau_bt = timing_tau_mat[ages_chr, years_chr, drop = FALSE]

  if (timeable_share == 0 || H == 0) {
    R_planned_S = R_planned_B
  } else {
    for (i in seq_len(n_ages)) {
      for (j in seq_len(n_years)) {
        amount = R_planned_B[i, j]
        if (amount == 0) next

        eligible = max(1, j - H):min(n_years, j + H)
        tau_vals = tau_bt[i, eligible]
        min_tau  = min(tau_vals, na.rm = TRUE)

        if (tau_bt[i, j] <= min_tau + tie_tol) {
          R_planned_S[i, j] = R_planned_S[i, j] + amount
        } else {
          candidates = eligible[tau_vals <= min_tau + tie_tol]
          distances  = abs(candidates - j)
          nearest    = candidates[distances == min(distances)]
          dest       = min(nearest)

          tax_saving = tau_bt[i, j] - tau_bt[i, dest]
          move_share = min(max(tax_saving / ref_wedge, 0), 1)
          moved      = amount * move_share

          R_planned_S[i, dest] = R_planned_S[i, dest] + moved
          R_planned_S[i, j]    = R_planned_S[i, j]    + (amount - moved)
        }
      }
    }
  }

  list(R_planned_B = R_planned_B,
       R_planned_S = R_planned_S,
       planned_timing_shift = R_planned_S - R_planned_B)
}



kg_dyn_build_scenario_rate = function(baseline_t, r_ordinary_S,
                                      R_planned_B_col, R_planned_S_col) {

  G_B = baseline_t$G_B
  r_B = baseline_t$r_B

  r_planned_B  = ifelse(G_B > 0, R_planned_B_col / G_B, 0)
  r_planned_S  = ifelse(G_B > 0, R_planned_S_col / G_B, 0)
  # Single pool: the level rate the Bellman anchors on is the full baseline rate.
  r_ordinary_B = r_B

  # Full-pool Bellman level response (r_ordinary_S = pass2 r_D) plus the NET
  # short-run timing shift. The shift nets to zero under a uniform permanent
  # shock (no year is cheaper), so it leaves the long-run level response intact;
  # at baseline r_ordinary_S = r_B and r_planned_S = r_planned_B, so r_S = r_B.
  r_S_unclipped = r_ordinary_S + (r_planned_S - r_planned_B)
  r_S           = pmin(pmax(r_S_unclipped, 0), 1)

  list(r_S            = r_S,
       r_S_unclipped  = r_S_unclipped,
       timing_clipped = abs(r_S - r_S_unclipped) > 1e-12,
       r_planned_B    = r_planned_B,
       r_planned_S    = r_planned_S,
       r_ordinary_B   = r_ordinary_B,
       r_ordinary_S   = r_ordinary_S)
}



#-------------------------------------------------------------------------------
# Bathtub recurrence step
#-------------------------------------------------------------------------------

kg_dyn_cell_m_eff = function(baseline_t) {

  # Effective cell mortality m_eff = sum(w*m*X) / sum(w*X). The death
  # channel needs sum_i w_i * m_i * (G_unit_i + dG_i); the naive cell-mean
  # form m * (G_B + dG) overstates that by ~2.7x in our data due to a
  # large negative within-cell Cov(m, G_unit) (wealth-mortality gradient).
  # Allocating dG_i proportional to X_i and summing analytically gives an
  # exact per-record sum, not an approximation. Two rules via
  # KG_DYN_DG_ALLOCATION: "G" (X = G_unit) or "R" (X = pmax(kg_lt, 0),
  # falling back to "G" when R_B = 0).
  #
  # Shared by kg_dyn_step_recurrence and the tau_eq machinery
  # (kg_dyn_tau_eq_primitives) so the two stay in lockstep on what
  # mortality the delta stock experiences.

  m_eff_G = if_else(baseline_t$G_B > 0,
                    baseline_t$mG_record / baseline_t$G_B, baseline_t$m)
  m_eff_R = if_else(baseline_t$R_B > 0,
                    baseline_t$mR_record / baseline_t$R_B, m_eff_G)

  m_eff = switch(KG_DYN_DG_ALLOCATION,
                 G = m_eff_G,
                 R = m_eff_R,
                 stop("Unknown KG_DYN_DG_ALLOCATION rule: ", KG_DYN_DG_ALLOCATION))
  pmin(pmax(m_eff, 0), 1)
}



kg_dyn_step_recurrence = function(delta_prev, baseline_t, A, omega,
                                  r_S_vec, delta_route_vec,
                                  conv_inflow_vec = NULL) {

  # One-step bathtub recurrence for delta_G on the [18, 80] grid. r_S_vec is
  # the scenario realization rate: the full-pool Bellman level response plus
  # the retimed short-run timing overlay.
  # delta_route_vec is a length-n_ages cell-level share of the dying stock
  # that routes to heirs (carryover); under per-asset regime mixing it's
  # produced by kg_dyn_build_regime_mix as sum_k share_k(a) * route_k.
  #
  # conv_inflow_vec (optional): length-n_ages vector of sigma-conversion
  # dollars entering the gain state at END of year t (the inheritance-inflow
  # convention, DESIGN_LOCK R6): it joins delta_next directly, participating
  # in realization/death dynamics from t+1 onward. NULL = no conversion
  # channel (identical output).
  #
  # Topcode caveat: the age=80 cell pools all 80+ taxpayers with a single
  # weight-averaged m_80, refreshed from each year's Tax-Data. Within-pool
  # heterogeneity (e.g., 15-year topcode residents vs. newly aged-in) is
  # smoothed out — small effect in practice but worth flagging if reforms
  # shift the topcode age mix.

  G_B       = baseline_t$G_B
  r_B       = baseline_t$r_B
  p_char    = pmin(pmax(baseline_t$p_char, 0), 1)

  m_eff = kg_dyn_cell_m_eff(baseline_t)

  r_S = pmin(pmax(r_S_vec, 0), 1)

  # Survivor flow (spec §3.2)
  inner      = (1 - r_S) * delta_prev + G_B * (r_B - r_S)
  contrib_a  = (1 - m_eff) * inner
  delta_surv = as.numeric(crossprod(A, contrib_a))

  # Inheritance flow (spec §3.3.1). delta_route_vec is per-cell so a cell
  # whose regime mix has no carryover share contributes nothing to the
  # routing crossprod even when adjacent cells do.
  decedent_stock      = m_eff * (G_B + delta_prev)
  terminal_char_stock = p_char * decedent_stock
  taxable_death_stock = (1 - p_char) * decedent_stock
  if (any(delta_route_vec > 0)) {
    delta_inh = as.numeric(crossprod(omega,
                                     delta_route_vec * taxable_death_stock))
  } else {
    delta_inh = rep(0, length(delta_prev))
  }

  # Sigma-conversion inflow: converted compensation enters the gain state at
  # end of year (participates from t+1, like the inheritance inflow).
  conv_inflow = if (is.null(conv_inflow_vec)) {
    rep(0, length(delta_prev))
  } else {
    stopifnot(length(conv_inflow_vec) == length(delta_prev))
    as.numeric(conv_inflow_vec)
  }

  list(delta_next = delta_surv + delta_inh + conv_inflow,
       r_S        = r_S,
       delta_surv = delta_surv,
       delta_inh  = delta_inh,
       conv_inflow = conv_inflow,
       decedent_stock      = decedent_stock,
       terminal_char_stock = terminal_char_stock,
       taxable_death_stock = taxable_death_stock)
}



#-------------------------------------------------------------------------------
# tau_eq: expected PV tax per dollar entering the gain state
#
# The equity leg of the sigma income-conversion wedge (top-tax exercise; see
# other/top_tax/DESIGN_LOCK.md rulings 1 and 6). tau_eq(a, t) prices a dollar
# injected into cell (age a, year t)'s deviation stock at END of year t (the
# inheritance-inflow convention, same as the conversion inflow itself), as the
# present value of tax the kg machinery actually collects on it:
#
#   - realization tax r_S * tau on the FULL stock each year (matching
#     extra_R = r_S * dG in kg_dyn_build_cell_table — r_S is the full-pool
#     scenario rate incl. the retimed short-run timing overlay);
#   - deaths take the full stock (decedents do not realize in-year, matching
#     the recurrence event order): the taxable share (1 - p_char) * m_eff
#     splits by regime mix — delta_realize taxed at tau at death (deemed),
#     delta_route routed to heir cells via omega and taxed there in later
#     years (FULL heir taxes, no theta -- tau_eq is a tax-price, not the
#     holder-internalized Bellman burden), delta_vanish forgiven (step-up).
#
# Ground truth is the finite-difference harness (kg_dyn_tau_eq_finite_diff):
# forward-simulate the EXACT kg_dyn_step_recurrence marginal dynamics for a
# test dollar and accumulate discounted taxes. The production path is the
# linear backward recursion (kg_dyn_compute_tau_eq), which unit tests (and
# the SIGMA_TAU_EQ_FDCHECK=1 in-pass check) verify cell-by-cell against the
# finite difference:
#
#   T(a, j)      = c(a, j) + beta_j * [K_j T(., j+1)](a)
#   c(a, j)      = r_S*tau + m_eff*(1 - p_char)*delta_realize*tau
#   K_j          = diag((1-m_eff)(1-r_S)) A  +  diag(m_eff (1-p_char) route) omega
#   tau_eq(a, t_j) = beta_j * T(a, j+1)     (end-of-year entry: first events
#                                            in t+1, discounted back to t)
#
# Terminal condition mirrors the Bellman's stationary assumption: T at
# t_max + 1 solves the year-t_max stationary system (I - beta K) T = c, a
# contraction since row sums of beta*K are <= beta < 1.
#
# Deliberate approximations (documented, Bellman-consistent):
#   - taxes are priced at the cell-aggregate MTR tau (the record applier
#     allocates to records and taxes through the calculator; tau_eq is a
#     wedge input, not a revenue booking);
#   - the record-level deemed refinements (avoidance haircut, sec 121
#     netting) do NOT enter, mirroring their exclusion from c_phi/Bellman.
#-------------------------------------------------------------------------------

kg_dyn_tau_eq_primitives = function(baseline_cells, years, r_S_by_year,
                                    tau_bt_mat, mix_list, A, omega,
                                    ages_bathtub = KG_DYN_AGE_MIN:KG_DYN_AGE_MAX,
                                    h_bt_mat = NULL, e_bt_mat = NULL) {

  # Assembles the [age, year] primitive matrices on the bathtub grid that
  # both the tau_eq recursion and the finite-difference harness consume, so
  # the two code paths share inputs by construction.
  #
  # Parameters:
  #   - baseline_cells (list) : per-year cell tibbles (G_B, m, mG_record, ...)
  #   - years (int[])         : simulation years
  #   - r_S_by_year (list)    : per-year realization-rate vectors on the
  #                             bathtub grid (scenario: rate_info$r_S incl.
  #                             the retimed planned bucket; baseline: r_B)
  #   - tau_bt_mat (mat)      : [age, year] cell MTRs, bathtub slice
  #   - mix_list (list|NULL)  : per-year regime-mix tibbles (delta_route,
  #                             delta_realize); NULL = step-up everywhere
  #                             (the baseline-side assumption, mirroring
  #                             Pass 1's c_phi = 0)
  #   - A, omega (mat)        : aging and heir-routing operators
  #   - h_bt_mat (mat|NULL)   : [age, year] wealth-tax carrying cost
  #                             (bathtub slice of the packed h matrix,
  #                             post-KG_WEALTH_CARRY_SCALE); NULL = zeros
  #                             (baseline side — h_B == 0 by law, asserted
  #                             in kg_dyn_load_bathtub_inputs; and every
  #                             non-wealth scenario)
  #   - e_bt_mat (mat|NULL)   : [age, year] estate exposure of the death
  #                             value (bathtub slice of the packed e matrix;
  #                             gain-weighted cell mtr_estate_ded, clamped
  #                             to [0, 1]). LEG-PAIRED, unlike h: prims_B
  #                             must receive the baseline-law e_B (current
  #                             law HAS an estate tax) and prims_S the
  #                             reform-law e_S. NULL = zeros (isolated unit
  #                             tests only)
  #
  # Returns: list of [n_ages, n_years] matrices (m_eff, p_char, r_S, tau,
  #          route, realize, h, e) plus A, omega, ages, years.

  ages_chr  = as.character(ages_bathtub)
  years_chr = as.character(years)
  n_ages    = length(ages_bathtub)
  n_years   = length(years)

  blank = function() matrix(0, n_ages, n_years,
                            dimnames = list(ages_chr, years_chr))
  m_eff   = blank(); p_char = blank(); r_S = blank()
  route   = blank(); realize = blank()

  for (j in seq_len(n_years)) {
    bt = baseline_cells[[years_chr[j]]]
    stopifnot(identical(as.integer(bt$age), as.integer(ages_bathtub)))
    m_eff [, j] = kg_dyn_cell_m_eff(bt)
    p_char[, j] = pmin(pmax(bt$p_char, 0), 1)
    r_S   [, j] = pmin(pmax(as.numeric(r_S_by_year[[j]]), 0), 1)
    if (!is.null(mix_list)) {
      mix = mix_list[[j]]
      idx = match(ages_bathtub, mix$age)
      route  [, j] = mix$delta_route  [idx]
      realize[, j] = mix$delta_realize[idx]
    }
  }

  tau = tau_bt_mat[ages_chr, years_chr, drop = FALSE]

  h = if (is.null(h_bt_mat)) blank() else {
    stopifnot(identical(dim(h_bt_mat), c(n_ages, n_years)))
    h_bt_mat[ages_chr, years_chr, drop = FALSE]
  }

  e = if (is.null(e_bt_mat)) blank() else {
    stopifnot(identical(dim(e_bt_mat), c(n_ages, n_years)))
    e_bt_mat[ages_chr, years_chr, drop = FALSE]
  }

  list(m_eff = m_eff, p_char = p_char, r_S = r_S, tau = tau,
       route = route, realize = realize, h = h, e = e, A = A, omega = omega,
       ages = ages_bathtub, years = years)
}



kg_dyn_tau_eq_flow = function(prims, j) {

  # Per-dollar year-j tax flow on one dollar of unrealized gain — the SINGLE
  # source of the c vector for BOTH the tau_eq backward recursion
  # (kg_dyn_compute_tau_eq) and the finite-difference verifier
  # (kg_dyn_tau_eq_finite_diff), so recursion and FD stay in lockstep by
  # construction. Three terms:
  #   realization:   r_S * tau
  #   death events:  m_eff * (1 - p_char) * realize * tau * (1 - e)
  #   wealth carry:  (1 - m_eff) * (1 - r_S) * h   — the SURVIVING-unrealized
  #                  share pays the wealth-tax carrying cost h = tau_w*tau_cg
  #                  on the deferred liability it keeps in the wealth base.
  # Timing convention (matches the Bellman sweep's survivor gate): wealth tax
  # assessed on END-OF-YEAR holdings, so in-year realizers and decedents pay
  # no carrying cost for that year. h == 0 reproduces the pre-carry flow
  # bitwise (x + 0 is exact for finite x; verified, not assumed, in
  # other/kg_model_tests/test_tau_eq_wealth.R).
  #
  # Estate offset on the DEATH-REALIZE term only (leg-paired e = cell
  # mtr_estate_ded, clamped [0,1]): the death-triggered CG tax is deductible
  # against the taxable estate (Sec. 2053-style, gated by the
  # estate.income_tax_ded law switch baked into mtr_estate_ded), so a dollar
  # of deemed-realization tax collects only (1 - e) net of the estate-tax
  # offset. Deliberately NOT discounted:
  #   - the route term (carryover-to-heir): a DEFERRAL of basis, not a
  #     collection — no death-time income tax is stamped there, so there is
  #     no Sec. 2053 deduction to price.
  #   - the during-life r_S * tau term: CG tax paid during life also shrinks
  #     the future estate, but that channel is carried MECHANICALLY by the
  #     wealth bathtub (during-life tax payments enter F = dT0 - dY_exog and
  #     drain into the estate base at death); discounting here would
  #     double-count it. Demonstrated end-to-end by the one-record
  #     accounting test (other/kg_model_tests/test_estate_offset.R).
  #   - the wealth-carry h term: a during-life wealth-tax flow, same
  #     bathtub-carried logic.
  # e == 0 reproduces the pre-offset flow bitwise (x * (1 - 0) is exact).
  #
  # Balance-sheet basis note: net_worth = sum(value.*) - debts with NO
  # netting of the contingent CG liability — that non-deductibility is
  # exactly why the carrying cost exists. Two-path check on $1 of gain,
  # tau_w = w, tau_cg = tau:
  #   realize now : pay tau today; the (1 - tau) proceeds stay in the wealth
  #                 base and pay w*(1 - tau) per year.
  #   hold        : pay nothing today; the FULL dollar stays in the wealth
  #                 base and pays w*1 per year.
  #   difference  : holding costs w*tau = h per year of continued deferral.

  # Missing e (hand-built prims in unit tests) defaults to 0 — the exact
  # pre-offset flow; kg_dyn_tau_eq_primitives always materializes it.
  e_j = if (is.null(prims$e)) 0 else prims$e[, j]

  prims$r_S[, j] * prims$tau[, j] +
    prims$m_eff[, j] * (1 - prims$p_char[, j]) *
      prims$realize[, j] * prims$tau[, j] * (1 - e_j) +
    (1 - prims$m_eff[, j]) * (1 - prims$r_S[, j]) * prims$h[, j]
}



kg_dyn_compute_tau_eq = function(prims, beta_by_year) {

  # Linear backward recursion for tau_eq on the bathtub grid (see the block
  # comment above for the model and conventions). beta_by_year is the same
  # per-year real-rate discount series the Bellman uses.
  #
  # Returns: list(tau_eq, T, T_stationary), tau_eq and T both [age, year].

  n_ages  = length(prims$ages)
  n_years = length(prims$years)
  stopifnot(length(beta_by_year) == n_years)

  dimnm = list(as.character(prims$ages), as.character(prims$years))

  # Per-year tax flow per dollar of start-of-year stock (shared with the FD
  # verifier via kg_dyn_tau_eq_flow — incl. the wealth-tax carrying cost on
  # the surviving-unrealized share), and the two continuation operators
  # (survivor aging + heir routing). Deemed composition note: h rides the
  # survivor branch only; HEIR carrying is priced through tau_eq's routing
  # continuation (the routed dollar re-enters the flow at the heir cell,
  # where it pays h again while deferred) — never in the holder Bellman.
  # Same asymmetry as the existing "full heir taxes, no theta" convention.
  c_mat = matrix(0, n_ages, n_years, dimnames = dimnm)
  for (j in seq_len(n_years)) c_mat[, j] = kg_dyn_tau_eq_flow(prims, j)
  K_of = function(j) {
    surv_w  = (1 - prims$m_eff[, j]) * (1 - prims$r_S[, j])
    route_w = prims$m_eff[, j] * (1 - prims$p_char[, j]) * prims$route[, j]
    surv_w * prims$A + route_w * prims$omega   # vector * matrix scales rows
  }

  # Stationary terminal: T(., t_max + 1) under year-t_max primitives.
  T_stat = solve(diag(n_ages) - beta_by_year[n_years] * K_of(n_years),
                 c_mat[, n_years])

  T_mat  = matrix(0, n_ages, n_years, dimnames = dimnm)
  tau_eq = matrix(0, n_ages, n_years, dimnames = dimnm)

  T_next = T_stat
  for (j in n_years:1) {
    tau_eq[, j] = beta_by_year[j] * T_next
    T_mat [, j] = c_mat[, j] +
                  beta_by_year[j] * as.numeric(K_of(j) %*% T_next)
    T_next      = T_mat[, j]
  }

  list(tau_eq = tau_eq, T = T_mat, T_stationary = T_stat)
}



kg_dyn_tau_eq_finite_diff = function(prims, beta_by_year, j0,
                                     horizon = 500, tol = 1e-14) {

  # Ground-truth tau_eq for injections at end of year index j0 (DESIGN_LOCK
  # ruling 1): forward-simulate the exact kg_dyn_step_recurrence marginal
  # dynamics for a test dollar in every age cell simultaneously (identity
  # injection matrix; columns = injection age) and accumulate the PV of tax
  # collected, discounted back to year j0. Primitives are held at their
  # year-t_max values beyond the simulation horizon, matching the
  # recursion's stationary terminal assumption.
  #
  # Returns: length-n_ages vector, tau_eq_FD(a, j0).

  n_ages  = length(prims$ages)
  n_years = length(prims$years)

  delta  = diag(n_ages)                # [current age, injection age]
  pv     = numeric(n_ages)
  disc   = beta_by_year[j0]            # discounts year-(j0+1) taxes to j0
  tA     = t(prims$A)
  tOmega = t(prims$omega)

  for (step in seq_len(horizon)) {
    ju  = min(j0 + step, n_years)      # hold t_max primitives beyond horizon
    c_u = kg_dyn_tau_eq_flow(prims, ju)

    pv = pv + disc * as.numeric(crossprod(delta, c_u))

    # Exact marginal delta dynamics: survivors (1-m_eff)(1-r_S) age via A;
    # the routed share of the dying stock moves to heir cells via omega.
    surv_w  = (1 - prims$m_eff[, ju]) * (1 - prims$r_S[, ju])
    route_w = prims$m_eff[, ju] * (1 - prims$p_char[, ju]) * prims$route[, ju]
    delta   = tA %*% (surv_w * delta) + tOmega %*% (route_w * delta)

    disc = disc * beta_by_year[ju]
    if (max(colSums(abs(delta))) < tol) break
  }

  setNames(pv, as.character(prims$ages))
}



kg_dyn_check_tau_eq = function(tau_eq_mat, tau_bt_mat, side,
                               carry_slack = 0) {

  # In-pass sanity bounds: tau_eq is a (discounted, at-most-once-ish) tax on
  # one dollar, so it must be nonnegative and cannot meaningfully exceed the
  # max cell MTR. The 1.05 slack covers the model's own realization/death
  # event overlap (extra_R charges r_S on the full stock while deaths also
  # take it; overlap ~ r_S * m_eff per year).
  #
  # carry_slack: with an active wealth tax, the deferred dollar ALSO pays
  # the carrying cost h every surviving-unrealized year, so tau_eq can
  # legitimately exceed the pure-CG cap. Callers pass the OPERATOR bound
  # max(h) * rho / (1 - rho), rho = max over cells/years of
  # beta*(1 - m_eff)*(1 - r_S) — the actual survival-continuation weight
  # incl. mortality + realization exit (deliberately tighter than the bare
  # 1/(1 - beta) geometric bound, which is too loose to catch real bugs).
  # Zero when h = 0, so non-wealth runs keep the original cap exactly.

  max_tau = max(tau_bt_mat, na.rm = TRUE)
  if (any(!is.finite(tau_eq_mat))) {
    stop('kg_dynamics: non-finite tau_eq_', side, ' values.')
  }
  if (any(tau_eq_mat < -1e-9)) {
    stop('kg_dynamics: negative tau_eq_', side, ' values (min = ',
         format(min(tau_eq_mat)), ').')
  }
  if (any(tau_eq_mat > max_tau * 1.05 + carry_slack + 1e-9)) {
    stop('kg_dynamics: tau_eq_', side, ' exceeds 1.05 * max cell tau + ',
         'carry slack (max = ', format(max(tau_eq_mat)), ' vs tau cap ',
         format(max_tau), ', carry_slack ', format(carry_slack), ').')
  }
  invisible(TRUE)
}



kg_dyn_carry_slack = function(prims, beta_by_year) {

  # Operator bound on the wealth-carry contribution to tau_eq (see
  # kg_dyn_check_tau_eq): each surviving-unrealized year adds at most
  # max(h), discounted-and-survived at most rho per year, so the total
  # carry PV is bounded by max(h) * (rho + rho^2 + ...) = max(h)*rho/(1-rho).

  h_max = max(prims$h)
  if (h_max <= 0) return(0)
  surv = (1 - prims$m_eff) * (1 - prims$r_S)
  rho  = max(sweep(surv, 2, beta_by_year, `*`))
  stopifnot(is.finite(rho), rho >= 0, rho < 1)
  h_max * rho / (1 - rho)
}



#-------------------------------------------------------------------------------
# Cell-level regime mix (per-asset codes → per-age vanish/route/realize + c_phi)
#-------------------------------------------------------------------------------

kg_dyn_build_regime_mix = function(regime_codes, theta, baseline_t,
                                    ages_bathtub = KG_DYN_AGE_MIN:KG_DYN_AGE_MAX) {

  # Aggregates per-asset regime codes into cell-level multipliers via
  # gain-stock-weighted shares:
  #   share_k(a)              = G_B_k(a) / G_B(a)
  #   share_primary_above_cap = G_B_primary_above_cap(a) / G_B(a)
  #   delta_{vanish,route,realize}(a) = sum_k share_k(a) * triplet_k$*
  #
  # c_phi(a) (share of cell gain stock taxed at death, the death-state
  # burden share the holder internalizes in the Bellman):
  #   c_phi(a) = sum_{k, deemed}            live_share_k(a)
  #            + theta * sum_{k, carryover} live_share_k(a)   (route internalized)
  # where live_share_k = share_primary_above_cap for primary_home (§121-net),
  # share_k otherwise. §121 nets the exclusion cap under BOTH deemed and
  # carryover (see live_share in the regime loop below).
  #
  # regime_codes : named list of 5 integer codes (one per asset class).
  # theta        : scalar bequest motive in [0, 1].
  # baseline_t   : per-cell tibble with G_B, G_B_{class}, G_B_primary_above_cap.
  #
  # Returns tibble keyed by age with delta_vanish, delta_route, delta_realize,
  # c_phi — each on the bathtub grid [18, 80].

  asset_classes = KG_DYN_ASSET_CLASSES

  missing = setdiff(asset_classes, names(regime_codes))
  if (length(missing) > 0) {
    stop('kg_dyn_build_regime_mix: regime_codes missing asset classes: ',
         paste(missing, collapse = ', '))
  }

  resolve_triplet = function(code) {
    t = KG_DYN_REGIME_TRIPLET[[as.character(code)]]
    if (is.null(t)) {
      stop('kg_dyn_build_regime_mix: unknown regime code ', code,
           ' (expected 0=step_up, 1=carryover, 2=deemed_realization)')
    }
    t
  }
  triplets = lapply(asset_classes, function(k) resolve_triplet(regime_codes[[k]]))
  names(triplets) = asset_classes

  G_B = baseline_t$G_B
  safe_share = function(num) if_else(G_B > 0, num / G_B, 0)

  share = lapply(asset_classes,
                 function(k) safe_share(baseline_t[[paste0('G_B_', k)]]))
  names(share) = asset_classes
  share_primary_above_cap = safe_share(baseline_t$G_B_primary_above_cap)

  n_cells       = length(G_B)
  delta_vanish  = rep(0, n_cells)
  delta_route   = rep(0, n_cells)
  delta_realize = rep(0, n_cells)
  c_phi         = rep(0, n_cells)

  for (k in asset_classes) {
    tr = triplets[[k]]

    # §121 primary-residence exclusion. Under BOTH deemed realization and
    # carryover, only the above-cap primary-home gain is "live": deemed taxes
    # it on the decedent's final return; carryover routes it to heirs. Both are
    # modeled as a death-time basis step-up of up to the §121 cap, so the
    # below-cap portion never enters the taxable/routed stock. Under step-up the
    # whole home gain is forgiven, so §121 is moot (delta_vanish keeps the full
    # share). live_share is §121-net for primary_home, the full share otherwise.
    live_share = if (k == 'primary_home') share_primary_above_cap else share[[k]]

    delta_vanish  = delta_vanish  + share[[k]] * tr$vanish
    delta_route   = delta_route   + live_share * tr$route
    delta_realize = delta_realize + live_share * tr$realize

    # Carryover internalization: holder values theta of the routed stock
    # (§121-net for primary_home).
    c_phi = c_phi + theta * tr$route * live_share

    # Deemed realization burden share (§121-net for primary_home).
    c_phi = c_phi + tr$realize * live_share
  }

  tibble(
    age           = baseline_t$age,
    delta_vanish  = delta_vanish,
    delta_route   = delta_route,
    delta_realize = delta_realize,
    c_phi         = pmin(pmax(c_phi, 0), 1)
  )
}



#-------------------------------------------------------------------------------
# Per-record applier (pure allocator). Reads the precomputed cell_table from
# the bathtub state file and translates cell-level quantities into per-record
# kg_lt adjustments via three channels (spec §7.3):
#   rate     : kg_lt > 0 → kg_lt * rate_factor (= r_S/r_B, clamped to 1)
#   lock-in  : extra_R = r_S * dG, allocated by positive-kg_lt share if
#              R_B > 0, else by G_unit share, else skip
#   deemed   : asset-aware. For each asset class k:
#                contribution_k = realize_k * gain_k_i        (k ≠ primary)
#                contribution_primary = realize_primary *
#                                       pmax(0, gain_primary_i - sec121_i)
#              Summed and scaled by (G_B + dG)/G_B (deemed_factor) into
#              kg_deemed_full; kg_deemed = m_household * kg_deemed_full.
#              realize_k comes from regime$realize, the year-level per-asset
#              deemed indicators from the regime mix. Deemed gains do NOT
#              enter kg_lt — run_one_year prices them via a two-leg
#              expected-tax recompute (see kg_deemed comment below).
#-------------------------------------------------------------------------------

kg_dyn_apply_to_records = function(tax_units, cell_table, realize_by_asset) {

  # Pull just the columns the applier consumes from cell_table via a
  # vectorized match() — avoids hash-joining the ~35-column diagnostics
  # table (with all the Bellman/timing/regime columns) onto 220k records
  # per scenario-year.
  idx           = match(tax_units$age_cohort, cell_table$age)
  rate_factor   = cell_table$rate_factor  [idx]
  extra_R       = cell_table$extra_R      [idx]
  deemed_factor = cell_table$deemed_factor[idx]
  R_B           = cell_table$R_B          [idx]
  G_B           = cell_table$G_B          [idx]
  p_char        = cell_table$p_char       [idx]

  missing = setdiff(KG_DYN_ASSET_CLASSES, names(realize_by_asset))
  if (length(missing) > 0) {
    stop('kg_dyn_apply_to_records: realize_by_asset missing asset classes: ',
         paste(missing, collapse = ', '))
  }

  # Applier-only deemed avoidance haircut. Data-calibration constant
  # (KG_DYN_DEEMED_AVOIDANCE), NOT tax law. Scales the per-record deemed
  # contribution to reflect noncompliance / valuation games; does not touch
  # c_phi or the Bellman.
  if (!is.finite(KG_DYN_DEEMED_AVOIDANCE) ||
      KG_DYN_DEEMED_AVOIDANCE < 0 || KG_DYN_DEEMED_AVOIDANCE > 1) {
    stop(sprintf(
      'kg_dyn_apply_to_records: KG_DYN_DEEMED_AVOIDANCE must be in [0, 1]; got %s.',
      format(KG_DYN_DEEMED_AVOIDANCE)))
  }
  avoidance_keep = 1 - KG_DYN_DEEMED_AVOIDANCE

  # The avoidance haircut is a VALUE discount (valuation games mark down the
  # asset value; basis is unchanged), applied PER RECORD so cross-sectional
  # dispersion in basis/value is preserved: discounted gain = pmax(0, keep*value
  # - basis). A uniform average basis/value ratio would (Jensen, at the pmax(0)
  # kink) zero out a whole class once the mean basis/value exceeds keep, even
  # though the low-basis tail still has taxable gain. value.*/basis.* are on
  # tax_units (read by kg_dyn_attach_record_attrs); the result is a dollar gain
  # amount, so it still rides deemed_factor = (G_B + dG)/G_B for the dG
  # evolution -- we only need baseline value/basis at the record, never through
  # the recurrence. Equals the full gain stock at keep = 1. primary_home nets
  # the §121 exclusion off the discounted gain.
  needed = c(KG_DYN_ASSET_VALUE_COLS, KG_DYN_ASSET_BASIS_COLS)
  miss = setdiff(needed, names(tax_units))
  if (length(miss) > 0) {
    stop('kg_dyn_apply_to_records: tax_units missing value/basis columns: ',
         paste(miss, collapse = ', '))
  }
  disc_gain = function(cls) {
    v = replace_na(as.numeric(tax_units[[paste0('value.', cls)]]), 0)
    b = replace_na(as.numeric(tax_units[[paste0('basis.', cls)]]), 0)
    pmax(0, avoidance_keep * v - b)
  }
  sec121 = replace_na(as.numeric(tax_units$`pref.kg_sec121_excl`), 0)
  g_primary_above_cap = pmax(0, disc_gain('primary_home') - sec121)

  deemed_per_record =
      realize_by_asset[['equities']]      * disc_gain('equities') +
      realize_by_asset[['pass_throughs']] * disc_gain('pass_throughs') +
      realize_by_asset[['primary_home']]  * g_primary_above_cap +
      realize_by_asset[['other_home']]    * disc_gain('other_home') +
      realize_by_asset[['re_fund']]       * disc_gain('re_fund')

  # Resolve the allocation knob to a numeric weight on the G (holdings)
  # share: 'R' = 0 (historical), 'G' = 1, or a numeric blend in [0, 1].
  alpha_G = switch(KG_DYN_APPLIER_ALLOCATION,
                   R = 0,
                   G = 1,
                   suppressWarnings(as.numeric(KG_DYN_APPLIER_ALLOCATION)))
  if (!is.finite(alpha_G) || alpha_G < 0 || alpha_G > 1) {
    stop("kg_dyn_apply_to_records: KG_DYN_APPLIER_ALLOCATION must be 'R', ",
         "'G', or a number in [0, 1]; got '", KG_DYN_APPLIER_ALLOCATION, "'.")
  }

  tax_units %>%
    mutate(
      # Each share sums to 1 within an age cell (with cross-fallbacks when a
      # cell has no realizations / no gain stock), so any convex blend does
      # too.
      share_R = case_when(
        R_B > 0 ~ pmax(kg_lt, 0) / R_B,
        G_B > 0 ~ G_unit         / G_B,
        TRUE    ~ 0
      ),
      share_G = case_when(
        G_B > 0 ~ G_unit         / G_B,
        R_B > 0 ~ pmax(kg_lt, 0) / R_B,
        TRUE    ~ 0
      ),
      allocation = (1 - alpha_G) * share_R + alpha_G * share_G,
      # Decomposition columns:
      #   kg_lockin      — this record's share of the cell's realized dG stock
      #                    (extra_R). In the conventional pass this blends
      #                    lock-in and carryover survival; in the mechanical
      #                    frozen pass (r_S = r_B) it is pure carryover
      #                    realization. Enters kg_lt directly.
      #   kg_deemed_full — the record's full deemed death gain (post-
      #                    avoidance, §121-net, scaled by deemed_factor):
      #                    what lands on the final return IF the household
      #                    dies this year. NOT added to kg_lt here.
      #   kg_deemed      — m_household * kg_deemed_full, the expected deemed
      #                    gain (diagnostics / ETR denominators / heir
      #                    reattribution identification).
      # Deemed death gains deliberately do NOT enter kg_lt. A stochastic
      # decedent draw puts ~±50% sampling error on deemed revenue (expected
      # death gains are concentrated in a few records, and a draw fixed
      # across years makes the error persistent); a fractional m*G injection
      # linearizes the rate schedule (Jensen: taxes m*G at the inter-vivos
      # margin instead of averaging the alive/dead outcomes). Instead,
      # run_one_year computes liab_deemed = m * [T(y + kg_deemed_full) -
      # T(y)] via a second full-frame recompute — the exact expectation with
      # record-level nonlinearity intact — and folds it into liab_iit_net.
      # The kg_lt frame stays alive-leg, so MTRs and tau are pure
      # inter-vivos margins.
      kg_lockin      = extra_R * allocation,
      kg_deemed_full = (1 - p_char) * deemed_factor * deemed_per_record,
      kg_deemed      = m_household * kg_deemed_full,
      kg_lt = if_else(kg_lt > 0, kg_lt * rate_factor, kg_lt) +
              kg_lockin
    ) %>%
    select(-allocation, -share_R, -share_G)
}



