# spec_version, macro_vintage) are FORM-INVARIANT and stay shared. The
# calibrated pair (eta, timeable_share) is PER FORM: each form is an
# independent calibration to the same local moment (E_full = -2.52). The guard
# compares only the LIVE form's pair (KG_RESPONSE_FORM).
# NOTE: the levels eta was RE-PINNED 2026-07-12 directly on the full simulator
# (E_full line inversion; see the KG_DYN_DEFAULT_ETA header + other/top_tax/
# eta_dial/eta_repin_fit.csv), NOT via calibrate.R (now a drift diagnostic). The
# re-pin was measured on Tax-Data 2026070814 (the production default). The
# levels timeable_share is carried from the 2026-07-09 short-run calibration (a
# timing overlay, robust to the Tax-Data vintage); its own derivation vintage
# (2026050315) is tracked separately in
# other/kg_model_tests/calibration_reference.csv. The logs pair is NA until the
