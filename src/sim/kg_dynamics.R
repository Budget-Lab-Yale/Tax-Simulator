# Realization RESPONSE FORM -- how the scenario-side FOC extrapolates away from
# the calibrated local moment. The entropy Bellman admits two cost primitives
# that fit the SAME local elasticity equally well but extrapolate differently
# (first-order for revenue-maximizing-rate questions); the choice is an
# extrapolation prior, selectable at run time via KG_RESPONSE_FORM (env
# propagates to every SLURM phase for free under --export=ALL):
#   'logs' (DEFAULT since 2026-07-20) -- constant NET-OF-TAX elasticity
#       (Agersnap-Zidar's preferred spec): log(r_D) is linear in log(1 - MC),
#       r_D = r_D_B * ((1 - MC)/(1 - MC_B))^eta_tilde. Generated by a convex
#       power cost with the same C'(r_D_B) = 0 anchor, so Pass-1 inversion,
#       appliers, tau_eq, and the h/e legs all carry over unchanged. Its own
#       independent calibration (eta_tilde AND timeable share), pinned 2026-07-19
#       (eta_tilde = 1.6625, timeable_share = 0.2542). Made the default per the
#       Yagan functional-form review: net-of-tax is the better-motivated
#       extrapolation prior for revenue-maximizing-rate questions and lowers the
#       step-up revmax relative to the semi form. NOTE: every downstream vintage
#       built before this flip used 'levels'; regenerate (or set
#       KG_RESPONSE_FORM=levels) before comparing against them.
#   'levels' -- constant SEMI-elasticity: log(r_D) is linear in the structural
#       wedge MC, r_D = r_D_B * exp(-eta*(MC - MC_B)). The joint consequence of a
#       linear payoff + KL/entropy realization cost; eta IS the long-run
#       semi-elasticity. This is the pre-toggle v3 calibration and the 'levels'
#       code path is BIT-IDENTICAL to it.
# Both forms cross at the baseline point by construction (C'(r_D_B) = 0 => the
# baseline pass is form-invariant, which the levels byte-identity run proves).
KG_DYN_RESPONSE_FORM    = local({
  v = Sys.getenv('KG_RESPONSE_FORM', 'logs')
  if (!v %in% c('levels', 'logs'))
    stop(sprintf(paste0("kg_dynamics: KG_RESPONSE_FORM must be 'levels' or ",
                        "'logs'; got '%s'."), v))
  v
})

# Net-of-tax domain cap: the 'logs' response (1 - MC)^eta_tilde is undefined as
# MC -> 1. Refuse to run (never clamp silently) if any cell's marginal cost MC
# or baseline marginal cost MC_B reaches this. Production MCs sit well below
# (tau ~ 0.238 plus a discounted continuation); a hit signals a broken discount
# series or death-continuation, not a real economy. Levels is unconstrained.
